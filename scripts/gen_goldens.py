"""
Generate golden file for Mag operation tests using mpmath's low-level library
with directed rounding to 64 bits.
"""

import os
from mpmath.libmp import from_man_exp, mpf_add, mpf_sub, mpf_mul, mpf_div, mpf_sqrt, fzero

I64_MIN = -2**63
I64_MAX = 2**63 - 1
TWO63 = 2**63
MASK64 = 2**64 - 1

RNDUP = 'c'
RNDDOWN = 'f'

def to_mpf(mag):
    exp, mant = mag
    return fzero if mant == 0 else from_man_exp(mant, exp - 64)

def from_mpf(x, up):
    sign, man, exp, bc = x
    if man == 0:
        return (0, 0)
    
    # Shift mantissa to 64-bit precision
    mant = man << (64 - bc)
    E = exp + bc
    
    if E > I64_MAX:
        if up:
            return "inf"
        else:
            return None
    elif E < I64_MIN:
        if up:
            return (I64_MIN, TWO63)
        else:
            return (0, 0)
    else:
        return (E, mant)

def mag_lt_or_eq(a, b):
    if a[1] == 0:
        return True
    if b[1] == 0:
        return False
    return a[0] < b[0] or (a[0] == b[0] and a[1] <= b[1])

def add_up(a, b):
    return from_mpf(mpf_add(to_mpf(a), to_mpf(b), 64, RNDUP), True)

def mul_up(a, b):
    return from_mpf(mpf_mul(to_mpf(a), to_mpf(b), 64, RNDUP), True)

def mul_lower(a, b):
    return from_mpf(mpf_mul(to_mpf(a), to_mpf(b), 64, RNDDOWN), False)

def sub_lower(a, b):
    if mag_lt_or_eq(a, b):
        return (0, 0)
    return from_mpf(mpf_sub(to_mpf(a), to_mpf(b), 64, RNDDOWN), False)

def div_up(a, b):
    return from_mpf(mpf_div(to_mpf(a), to_mpf(b), 64, RNDUP), True)

def div_lower(a, b):
    return from_mpf(mpf_div(to_mpf(a), to_mpf(b), 64, RNDDOWN), False)

def sqrt_up(a):
    return from_mpf(mpf_sqrt(to_mpf(a), 64, RNDUP), True)

def sqrt_lower(a):
    return from_mpf(mpf_sqrt(to_mpf(a), 64, RNDDOWN), False)

MANTS = [TWO63, TWO63 + 1, MASK64]
EXPS = [-65, -64, -63, 0, 63, 64, 65, I64_MIN, I64_MIN + 1, I64_MAX - 1, I64_MAX]
SET = [(0, 0)] + [(e, m) for e in EXPS for m in MANTS]

def main():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "goldens", "mag_ops.txt")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    
    with open(path, "w") as f:
        f.write("# zenith-bound Mag operation goldens, generated by scripts/gen_goldens.py (mpmath.libmp directed rounding to 64 bits)\n")
        f.write("# binary: OP EA MA EB MB R ; unary: OP E M R ; R is 'ER MR' or the word inf\n")
        f.write("# value = mant * 2^(exp - 64); zero is '0 0'\n")
        
        ops = [
            ("add_up", 2),
            ("mul_up", 2),
            ("mul_lower", 2),
            ("sub_lower", 2),
            ("div_up", 2),
            ("div_lower", 2),
            ("sqrt_up", 1),
            ("sqrt_lower", 1)
        ]
        
        line_count = 3
        
        for op_name, num_args in ops:
            if num_args == 2:
                for a in SET:
                    for b in SET:
                        if op_name in ["div_up", "div_lower"] and b[1] == 0:
                            continue
                        if op_name == "add_up":
                            result = add_up(a, b)
                        elif op_name == "mul_up":
                            result = mul_up(a, b)
                        elif op_name == "mul_lower":
                            result = mul_lower(a, b)
                        elif op_name == "sub_lower":
                            result = sub_lower(a, b)
                        elif op_name == "div_up":
                            result = div_up(a, b)
                        elif op_name == "div_lower":
                            result = div_lower(a, b)
                        else:
                            raise ValueError(f"Unknown binary operation: {op_name}")
                        
                        if result is None:
                            continue
                        if isinstance(result, str):
                            f.write(f"{op_name} {a[0]} {a[1]} {b[0]} {b[1]} {result}\n")
                        else:
                            f.write(f"{op_name} {a[0]} {a[1]} {b[0]} {b[1]} {result[0]} {result[1]}\n")
                        line_count += 1
            else:  # unary operations
                for a in SET:
                    if op_name == "sqrt_up":
                        result = sqrt_up(a)
                    elif op_name == "sqrt_lower":
                        result = sqrt_lower(a)
                    else:
                        raise ValueError(f"Unknown unary operation: {op_name}")
                    
                    if result is None:
                        continue
                    if isinstance(result, str):
                        f.write(f"{op_name} {a[0]} {a[1]} {result}\n")
                    else:
                        f.write(f"{op_name} {a[0]} {a[1]} {result[0]} {result[1]}\n")
                    line_count += 1
    
    print(line_count)

if __name__ == "__main__":
    main()
