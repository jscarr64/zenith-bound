//! The committed golden files and the header line each must start with. The sha256 comparison is NOT done in Rust (no hashing crate may be
//! added); the shell gate step tools/goldens_regen.sh runs `sha256sum -c tests/goldens/SHA256SUMS` and regenerates every file byte for byte.

use std::path::PathBuf;

pub struct GoldenFile {
    pub name: &'static str,
    pub header: &'static str,
}

/// Every golden file in tests/goldens/, with the exact first line its generator writes. A new golden file needs a row here, a line in
/// tests/goldens/SHA256SUMS and a generator in tools/goldens_regen.sh.
pub const GOLDEN_FILES: [GoldenFile; 3] = [
    GoldenFile {
        name: "ball_exact_ops.txt",
        header: "# zenith-bound L0b exact-input ball goldens, generated by scripts/gen_ball_goldens.py (generator version 1)",
    },
    GoldenFile {
        name: "mag_ops.txt",
        header: "# zenith-bound Mag operation goldens, generated by scripts/gen_goldens.py (mpmath.libmp directed rounding to 64 bits)",
    },
    GoldenFile {
        name: "mag_ops_review.txt",
        header: "# zenith-bound Mag review boundary rows, generated by scripts/gen_review_goldens.py (independent big-integer oracle)",
    },
];

pub fn golden_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("goldens")
}
